const { contextBridge, ipcRenderer } = require('electron');

const ALLOWED_EVENTS = ['metrics', 'stream:ended', 'ffmpeg:log', 'tv:state', 'tv:closed', 'rtc:signal', 'media:changed', 'web:frame', 'web:state', 'remote:snap', 'remote:call'];

contextBridge.exposeInMainWorld('api', {
  captureSources: (light) => ipcRenderer.invoke('capture:sources', !!light),
  captureSelect: (id) => ipcRenderer.invoke('capture:select', id),
  bootProgress: (pct, text) => ipcRenderer.send('boot:progress', pct, text),
  bootLoaded: () => ipcRenderer.send('boot:loaded'),
  listDisplays: () => ipcRenderer.invoke('displays:list'),
  openTv: (id) => ipcRenderer.invoke('tv:open', id),
  closeTv: (id) => ipcRenderer.invoke('tv:close', id),
  setTv: (id, state) => ipcRenderer.send('tv:set', id, state),
  rtcSignal: (a, b) => ipcRenderer.send('rtc:signal', b === undefined ? { msg: a } : { id: a, msg: b }), // from the operator: (screen id, message). From an external window: (message)
  getLayout: () => ipcRenderer.invoke('layout:get'),
  setLayout: (l) => ipcRenderer.invoke('layout:set', l),
  webOpen: (url) => ipcRenderer.invoke('web:open', url),
  webClose: () => ipcRenderer.invoke('web:close'),
  webNav: (a) => ipcRenderer.send('web:nav', a),
  webInput: (ev) => ipcRenderer.send('web:input', ev),
  checkFfmpeg: () => ipcRenderer.invoke('ffmpeg:check'),
  startStream: (opts) => ipcRenderer.invoke('stream:start', opts),
  sendChunk: (buf) => ipcRenderer.send('stream:chunk', buf),
  stopStream: () => ipcRenderer.invoke('stream:stop'),
  logRow: (row) => ipcRenderer.send('log:row', row),
  openRecordings: () => ipcRenderer.invoke('recordings:open'),
  appName: () => ipcRenderer.invoke('app:name'),
  recDir: () => ipcRenderer.invoke('recordings:dir'),
  setRecDir: (d) => ipcRenderer.invoke('recordings:setDir', d),
  chooseRecDir: () => ipcRenderer.invoke('recordings:choose'),
  diskFree: () => ipcRenderer.invoke('disk:free'),
  recovered: () => ipcRenderer.invoke('app:recovered'),
  ytStatus: () => ipcRenderer.invoke('yt:status'),
  ytSetClient: (id, secret) => ipcRenderer.invoke('yt:setClient', id, secret),
  ytSignIn: () => ipcRenderer.invoke('yt:signIn'),
  ytSignOut: () => ipcRenderer.invoke('yt:signOut'),
  ytPrepare: (tpl) => ipcRenderer.invoke('yt:prepare', tpl),
  ytEnd: (id) => ipcRenderer.invoke('yt:end', id),
  ytExpand: (text) => ipcRenderer.invoke('yt:expand', text),
  bibleFetch: (ref, trans) => ipcRenderer.invoke('bible:fetch', ref, trans),
  mediaGet: () => ipcRenderer.invoke('media:get'),
  mediaScan: () => ipcRenderer.invoke('media:scan'),
  mediaChoose: () => ipcRenderer.invoke('media:choose'),
  mediaClear: () => ipcRenderer.invoke('media:clear'),
  mediaOpen: () => ipcRenderer.invoke('media:open'),
  ltList: () => ipcRenderer.invoke('lt:list'),
  ltImport: () => ipcRenderer.invoke('lt:import'),
  ltRemove: (id) => ipcRenderer.invoke('lt:remove', id),
  ltOpen: () => ipcRenderer.invoke('lt:open'),
  openLogs: () => ipcRenderer.invoke('logs:open'),
  logDir: () => ipcRenderer.invoke('logs:dir'),
  remoteReply: (id, data) => ipcRenderer.send('remote:reply', id, data),
  remoteSetPin: (pin) => ipcRenderer.send('remote:setPin', pin),
  remoteAddress: () => ipcRenderer.invoke('remote:address'),
  finishRecording: (files) => ipcRenderer.invoke('recordings:finish', files),
  settingsLoad: () => ipcRenderer.sendSync('settings:load'),
  settingsSave: (json) => ipcRenderer.sendSync('settings:save', json),
  on: (channel, cb) => {
    if (ALLOWED_EVENTS.includes(channel)) ipcRenderer.on(channel, (e, data) => cb(data));
  },
});
